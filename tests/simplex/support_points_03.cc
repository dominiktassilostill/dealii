template <int dim>
void
test(const unsigned int                         degree,
     const std::vector<std::vector<Point<dim>>> solutions)
{
  const double tol = 1e-12;

  // given solution
  const std::vector<Point<dim>> points_given = solutions[degree - 1];
  const FE_SimplexP<dim>        fe(degree);
  const std::vector<Point<dim>> points = fe.get_unit_support_points();

  // go over all points
  for (const auto &p : points)
    {
      bool point_exists = false;
      for (const auto &p_other : points_given)
        if (p.distance(p_other) < tol)
          point_exists = true;

      if (point_exists == false)
        {
          deallog << "This point is wrong " << p << std::endl;
          DEAL_II_ASSERT_UNREACHABLE();
        }
    }
  deallog << "Found all points of degree: " << degree << std::endl;
}


